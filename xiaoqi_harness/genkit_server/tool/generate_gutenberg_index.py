"""Generate the Chinese title index from Project Gutenberg's official CSV.

Usage: python generate_gutenberg_index.py pg_catalog.csv.gz TSCharacters.txt
TSPhrases.txt ../lib/src/gutenberg_chinese_titles.dart

Use the catalog from https://gutenberg.pglaf.org/cache/epub/feeds/ and the
traditional-to-simplified dictionaries from OpenCC ver.1.1.9 (Apache-2.0).
The index contains discovery keys only. Rights and contents are checked online.
"""

import csv
import gzip
import hashlib
import json
import re
import sys
from collections import defaultdict
from pathlib import Path


def dictionary(path):
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if "\t" in line and not line.lstrip().startswith("#"):
            source, targets = line.split("\t", 1)
            yield source, targets.split()[0]


def key(title):
    return re.sub(r"[^a-z0-9\u3400-\u9fff]", "", title.lower())


catalog, characters, phrases, output = sys.argv[1:]
aliases = dict(dictionary(characters)) | dict(dictionary(phrases))
pattern = re.compile("|".join(re.escape(phrase) for phrase in sorted(aliases, key=len, reverse=True)))
index = defaultdict(set)
with gzip.open(catalog, "rt", encoding="utf-8-sig", newline="") as source:
    for row in csv.DictReader(source):
        if row["Type"] != "Text" or row["Language"] != "zh":
            continue
        title = row["Title"]
        if not re.search(r"[\u3400-\u9fff]", title):
            continue
        simplified = pattern.sub(lambda match: aliases[match[0]], title)
        for name in (key(title), key(simplified)):
            index[name].add(int(row["Text#"]))

with Path(output).open("w", encoding="utf-8", newline="\n") as target:
    print("// Generated by tool/generate_gutenberg_index.py from the Gutenberg CSV.", file=target)
    print("// Compressed catalog SHA-256:", file=target)
    print(f"// {hashlib.sha256(Path(catalog).read_bytes()).hexdigest()}", file=target)
    print("const gutenbergChineseTitles = <String, List<int>>{", file=target)
    for title, ids in sorted(index.items()):
        print(f"  {json.dumps(title, ensure_ascii=False)}: {sorted(ids)},", file=target)
    print("};", file=target)
